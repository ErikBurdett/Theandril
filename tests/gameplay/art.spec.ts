test('Art Lab refuses stale, mismatched and oversized atlas images before reporting pixel measurements', async ({ page }) => {
  await begin(page);
  await expect.poll(() => page.evaluate(() => window.__THEANDRIL__?.getArtDiagnostics()?.state)).toBe('ready');
  const before = await page.evaluate(() => window.__THEANDRIL__?.getStateHash());
  const catalog = parseRuntimeCatalog(await (await page.request.get('/art/catalog.json')).json());
  const atlas = catalog.atlases.find(item => item.id === catalog.assets.find(asset => asset.id === 'unit.guard')!.atlasId)!;
  const original = await (await page.request.get(atlas.imageUrl)).body();
  const pattern = `**${atlas.imageUrl}`;
  const corrupted = Buffer.from(original); corrupted[corrupted.length - 1] = corrupted[corrupted.length - 1]! ^ 1;
  await page.route(pattern, route => route.fulfill({ status: 200, contentType: 'image/png', body: corrupted }));
  await page.getByRole('button', { name: 'Art Lab', exact: true }).click();
  const lab = page.getByRole('dialog', { name: 'Art Lab', exact: true });
  await lab.getByLabel('Search art assets', { exact: true }).fill('unit.guard');
  await lab.getByRole('button', { name: 'Inspect unit.guard', exact: true }).click();
  await expect(lab.getByRole('alert')).toContainText('Atlas image hash mismatch');
  await expect(lab.getByTestId('art-preview-canvas')).toHaveCount(0);
  await expect(lab.getByTestId('art-pixel-metrics')).toHaveCount(0);
  await page.unroute(pattern);
  const mismatched = Buffer.from(original); mismatched.writeUInt32BE(atlas.width - 1, 16);
  await page.route(pattern, route => route.fulfill({ status: 200, contentType: 'image/png', body: mismatched }));
  await lab.getByRole('button', { name: 'Reload art catalog', exact: true }).click();
  await expect(lab.getByRole('alert')).toContainText('Atlas image dimensions mismatch');
  await expect(lab.getByTestId('art-pixel-metrics')).toHaveCount(0);
  await page.unroute(pattern);
  const oversized = Buffer.from(original); oversized.writeUInt32BE(8192, 16);
  await page.route(pattern, route => route.fulfill({ status: 200, contentType: 'image/png', body: oversized }));
  await lab.getByRole('button', { name: 'Reload art catalog', exact: true }).click();
  await expect(lab.getByRole('alert')).toContainText('4,096-pixel edge limit');
  await expect(lab.getByTestId('art-pixel-metrics')).toHaveCount(0);
  await expect(lab.getByTestId('art-preview-canvas')).toHaveCount(0);
  expect(await page.evaluate(() => window.__THEANDRIL__?.getStateHash())).toBe(before);
  expect(await page.evaluate(() => window.__THEANDRIL__?.getArtDiagnostics()?.state)).toBe('ready');
});
