import { expect, test } from '@playwright/test';
import { neighbors } from '@theandril/mapgen';
import { getMovementPreview, getObservation, stateHash } from '@theandril/sim';
import { campaignMenu, exportedTravel } from '../gameplay/group-movement-fixture';
import { closeManagement, openSelectedOrders, selectFromRegistry } from '../gameplay/ui-navigation';

test('a generated production campaign patrols, pauses and restores through real controls without development hooks', async ({ page }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('./');
  await page.getByRole('textbox', { name: 'World seed', exact: true }).fill('20260927');
  await page.getByRole('combobox', { name: 'World size', exact: true }).selectOption('tiny');
  await page.getByRole('spinbutton', { name: 'Faction count', exact: true }).fill('2');
  await page.getByRole('spinbutton', { name: 'City-states', exact: true }).fill('0');
  await page.getByRole('button', { name: 'Begin campaign', exact: true }).click();
  await expect(page.getByRole('button', { name: 'End turn', exact: true })).toBeEnabled();
  expect(await page.evaluate(() => typeof window.__THEANDRIL__)).toBe('undefined');
  const origin = await exportedTravel(page), view = getObservation(origin.game, origin.game.turnOwnerId);
  const army = view.armies.find(army => army.factionId === view.factionId && army.canAttack && !army.canFound && army.domain === 'land')!;
  expect(army).toBeTruthy();
  const target = neighbors(army.cell, view.width, view.height).find(cell => {
    const route = getMovementPreview(view, army.id, cell);
    return route.canQueue && route.action === 'move' && route.canMoveNow;
  });
  expect(target).toBeDefined();
  await selectFromRegistry(page, 'armies', army.name); await openSelectedOrders(page);
  const patrol = page.getByTestId('army-patrol'); await patrol.locator(':scope > summary').click();
  await patrol.getByRole('spinbutton', { name: 'Second patrol point', exact: true }).fill(String(target));
  await patrol.getByRole('button', { name: 'Start patrol', exact: true }).click();
  await closeManagement(page);
  await page.getByRole('button', { name: 'End turn', exact: true }).click();
  await expect(page.getByTestId('turn-counter')).toHaveText('Turn 2');
  await expect(page.getByRole('button', { name: 'End turn', exact: true })).toBeEnabled();
  const moving = await exportedTravel(page);
  expect(moving.game.armies[army.id]!.cell).toBe(target);
  expect(moving.game.patrols[0]!.target).toBe('first');
  await page.getByRole('button', { name: 'Save campaign', exact: true }).click();
  await expect(page.getByTestId('feedback')).toContainText('Campaign saved.');
  await selectFromRegistry(page, 'armies', army.name); await openSelectedOrders(page);
  await patrol.locator(':scope > summary').click();
  await patrol.getByRole('button', { name: 'Pause patrol', exact: true }).click();
  await expect(patrol.locator(':scope > summary')).toContainText('Paused');
  await campaignMenu(page);
  await page.getByRole('button', { name: 'Load campaign', exact: true }).click();
  await expect(page.getByTestId('feedback')).toContainText('Campaign restored.');
  const restored = await exportedTravel(page);
  expect(stateHash(restored.game)).toBe(stateHash(moving.game));
  expect(restored.archive).toEqual(moving.archive);
  await page.getByRole('combobox', { name: 'Text scale', exact: true }).selectOption('1.3');
  await page.setViewportSize({ width: 390, height: 844 });
  await selectFromRegistry(page, 'armies', army.name); await openSelectedOrders(page);
  await patrol.locator(':scope > summary').click();
  await patrol.getByRole('button', { name: 'Pause patrol', exact: true }).focus(); await page.keyboard.press('Enter');
  await expect(patrol.getByRole('button', { name: 'Resume patrol', exact: true })).toBeEnabled();
  const remove = patrol.getByRole('button', { name: 'Remove patrol', exact: true });
  await remove.scrollIntoViewIfNeeded();
  expect(await remove.evaluate(button => {
    const bounds = button.getBoundingClientRect(), frame = button.closest('.campaign-window-body')!.getBoundingClientRect();
    return bounds.top >= frame.top && bounds.bottom <= frame.bottom && bounds.left >= frame.left && bounds.right <= frame.right;
  })).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('production-patrol-narrow-large-text.png') });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
