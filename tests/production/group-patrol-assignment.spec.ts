import { neighbors } from '@theandril/mapgen';
import { writeFileSync } from 'node:fs';
import { expect, test } from '@playwright/test';
import { replayArchive, resumeJournal } from '@theandril/chronicle';
import { deserializeGame, getMovementPreview, getObservation, serializeGame, stateHash } from '@theandril/sim';
import { exportSave, serializeCampaign } from '@theandril/persistence';
import { groupPatrolScene } from '../gameplay/group-patrol-fixture';
import { campaignMenu, exportedTravel } from '../gameplay/group-movement-fixture';
import { closeCampaignOptions, closeManagement, openRegistry } from '../gameplay/ui-navigation';

test('production assigns shared patrol endpoints to 101 checked armies and preserves paused policies and existing travel', async ({ page }, testInfo) => {
  const fixture = groupPatrolScene(), expectedGame = deserializeGame(serializeGame(fixture.game));
  const journal = resumeJournal(expectedGame, fixture.archive);
  const armies = Object.values(fixture.game.armies).filter(army => army.factionId === fixture.factionId).sort((a, b) => a.id.localeCompare(b.id));
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('./');
  expect(await page.evaluate(() => '__THEANDRIL__' in window)).toBe(false);
  await page.getByLabel('Import save file').setInputFiles({ name: '101-patrol-assignments.theandril', mimeType: 'application/gzip', buffer: Buffer.from(await exportSave(serializeCampaign(fixture.game, fixture.archive))) });
  await expect(page.getByTestId('feedback')).toContainText('Imported campaign');
  await openRegistry(page, 'armies');
  const selection = page.getByTestId('group-postings'), panel = page.getByTestId('group-patrols');
  await selection.getByRole('button', { name: 'Select matching armies', exact: true }).click();
  await expect(selection).toContainText('101 armies selected');
  await page.getByRole('combobox', { name: 'Army orders', exact: true }).selectOption('paused-patrols');
  await panel.locator(':scope > summary').click();
  await expect(panel).toContainText('51 outside this filter');
  const form = page.getByTestId('group-patrol-assignment');
  await form.locator(':scope > summary').click();
  await expect(form.getByRole('button', { name: 'Assign patrols (101)', exact: true })).toBeDisabled();
  await form.getByLabel('First group patrol point', { exact: true }).fill('497');
  await form.getByLabel('Second group patrol point', { exact: true }).fill('495');
  await form.getByLabel('Pause assigned patrols when war begins', { exact: true }).check();
  await form.screenshot({ path: testInfo.outputPath('group-patrol-assignment-native.png') });
  await form.getByRole('button', { name: 'Assign patrols (101)', exact: true }).screenshot({ path: testInfo.outputPath('group-patrol-assignment-action-native.png') });
  await form.locator(':scope > summary').scrollIntoViewIfNeeded();
  const top = (await form.boundingBox())!, bottom = (await form.locator('select').last().boundingBox())!;
  await page.screenshot({ path: testInfo.outputPath('group-patrol-points-native.png'), clip: { x: top.x, y: top.y, width: top.width, height: bottom.y + bottom.height - top.y } });
  await page.screenshot({ path: testInfo.outputPath('group-patrol-assignment-desktop.png') });
  await form.getByRole('button', { name: 'Assign patrols (101)', exact: true }).click();
  await expect(page.getByTestId('group-patrol-results')).toContainText('101 patrol orders accepted · 0 refused');
  await expect(selection).toContainText('0 armies selected');
  for (const army of armies) expect(journal.record(expectedGame, { type: 'setPatrol', factionId: fixture.factionId, armyId: army.id, firstCell: 497, secondCell: 495, enabled: fixture.game.patrols.find(policy => policy.armyId === army.id)?.enabled ?? true, pauseOnWar: true }).ok).toBe(true);
  const assigned = await exportedTravel(page);
  expect(serializeGame(assigned.game)).toBe(serializeGame(expectedGame));
  expect(assigned.archive).toEqual(journal.materialize());
  expect(serializeGame(replayArchive(assigned.archive))).toBe(serializeGame(assigned.game));
  expect(assigned.archive.records).toHaveLength(206);
  expect(assigned.game.armies).toEqual(fixture.game.armies);
  expect(assigned.game.routes).toEqual(fixture.game.routes);
  expect(assigned.game.postings).toEqual(fixture.game.postings);
  expect(assigned.game.patrols.filter(policy => !policy.enabled)).toHaveLength(50);
  await campaignMenu(page);
  await page.getByRole('button', { name: 'Save campaign', exact: true }).click();
  await expect(page.getByTestId('feedback')).toContainText('Campaign saved');
  await page.getByRole('combobox', { name: 'Text scale', exact: true }).selectOption('1.3');
  await page.setViewportSize({ width: 390, height: 844 });
  await openRegistry(page, 'armies');
  await selection.getByRole('button', { name: 'Select matching armies', exact: true }).click();
  await panel.locator(':scope > summary').click();
  await form.locator(':scope > summary').click();
  await form.getByLabel('First group patrol point', { exact: true }).fill('495');
  await form.getByLabel('Second group patrol point', { exact: true }).fill('497');
  const submit = form.getByRole('button', { name: 'Assign patrols (101)', exact: true });
  await submit.scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('group-patrol-assignment-narrow-130.png') });
  await submit.focus(); await page.keyboard.press('Enter');
  await expect(page.getByTestId('group-patrol-results')).toContainText('101 patrol orders accepted · 0 refused');
  await campaignMenu(page);
  await page.getByRole('button', { name: 'Load campaign', exact: true }).click();
  await expect(page.getByTestId('feedback')).toContainText('Campaign restored');
  const restored = await exportedTravel(page);
  expect(serializeGame(restored.game)).toBe(serializeGame(assigned.game));
  expect(restored.archive).toEqual(assigned.archive);
  writeFileSync(testInfo.outputPath('assigned.theandril'), assigned.bytes);
  writeFileSync(testInfo.outputPath('restored.theandril'), restored.bytes);
  writeFileSync(testInfo.outputPath('assignment.json'), JSON.stringify({ initialHash: fixture.hash, assignedHash: stateHash(assigned.game), restoredHash: stateHash(restored.game), records: assigned.archive.records.length, policies: assigned.game.patrols.length, paused: assigned.game.patrols.filter(policy => !policy.enabled).length }, null, 2) + '\n');
  expect(errors).toEqual([]);
});

// Separate generated campaign: prove an assigned policy actually travels both ways.
test('a group-assigned patrol travels out and back in a generated campaign', async ({ page }, testInfo) => {
  await page.goto('./');
  await page.getByRole('textbox', { name: 'World seed', exact: true }).fill('20260927');
  await page.getByRole('combobox', { name: 'World size', exact: true }).selectOption('tiny');
  await page.getByRole('spinbutton', { name: 'Faction count', exact: true }).fill('2');
  await page.getByRole('spinbutton', { name: 'City-states', exact: true }).fill('0');
  await page.getByRole('button', { name: 'Begin campaign', exact: true }).click();
  await expect(page.getByRole('button', { name: 'End turn', exact: true })).toBeEnabled();
  const origin = await exportedTravel(page), view = getObservation(origin.game, origin.game.turnOwnerId);
  const army = view.armies.find(army => army.factionId === view.factionId && army.canAttack && !army.canFound && army.domain === 'land')!;
  const target = neighbors(army.cell, view.width, view.height).find(cell => {
    const route = getMovementPreview(view, army.id, cell);
    return route.canQueue && route.action === 'move' && route.canMoveNow;
  });
  expect(target).toBeDefined();
  await openRegistry(page, 'armies');
  await page.getByRole('checkbox', { name: `Select ${army.name} for group orders`, exact: true }).check();
  const panel = page.getByTestId('group-patrols'), form = page.getByTestId('group-patrol-assignment');
  await panel.locator(':scope > summary').click();
  await form.locator(':scope > summary').click();
  await form.getByLabel('First group patrol point', { exact: true }).fill(String(army.cell));
  await form.getByLabel('Second group patrol point', { exact: true }).fill(String(target));
  await form.getByRole('button', { name: 'Assign patrols (1)', exact: true }).click();
  await expect(page.getByTestId('group-patrol-results')).toContainText('1 patrol orders accepted · 0 refused');
  await closeManagement(page);
  await page.getByRole('button', { name: 'End turn', exact: true }).click();
  await expect(page.getByTestId('turn-counter')).toHaveText('Turn 2');
  const outward = await exportedTravel(page);
  expect(outward.game.armies[army.id]!.cell).toBe(target);
  expect(outward.game.patrols.find(policy => policy.armyId === army.id)?.target).toBe('first');
  await closeCampaignOptions(page);
  await page.getByRole('button', { name: 'End turn', exact: true }).click();
  await expect(page.getByTestId('turn-counter')).toHaveText('Turn 3');
  const returned = await exportedTravel(page);
  expect(returned.game.armies[army.id]!.cell).toBe(army.cell);
  expect(returned.game.patrols.find(policy => policy.armyId === army.id)?.target).toBe('second');
  expect(serializeGame(replayArchive(returned.archive))).toBe(serializeGame(returned.game));
  writeFileSync(testInfo.outputPath('out-and-back.json'), JSON.stringify({ armyId: army.id, origin: army.cell, outward: outward.game.armies[army.id]!.cell, returned: returned.game.armies[army.id]!.cell, finalHash: stateHash(returned.game), records: returned.archive.records.length }, null, 2) + '\n');
});
